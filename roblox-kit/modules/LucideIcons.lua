local function getFilledModule(): any
	local sibling = script.Parent and script.Parent:FindFirstChild('LucideFilledIcons')
	if sibling and sibling:IsA('ModuleScript') then
		return (require :: any)(sibling)
	end
	return nil
end

function LucideIcons.get(name: string, filled: boolean?): string
	local clean = string.lower((string.gsub(name, '_', '-')))
	if filled or string.sub(clean, -5) == '-fill' then
		local fm = getFilledModule()
		if fm then
			local furi = fm.get(clean)
			if furi then return furi end
		end
		clean = string.gsub(clean, '%-fill$', '')
	end
	return IconMap[clean] or IconMap['sparkles'] or 'rbxassetid://7733960981'
end

function LucideIcons.search(query: string, limit: number?): { { name: string, uri: string } }
	local q = string.lower(query or '')
	local maxOut = limit or 25
	local out = {}
	for name, uri in pairs(IconMap) do
		if q == '' or string.find(name, q, 1, true) ~= nil then
			table.insert(out, { name = name, uri = uri })
			if #out >= maxOut then break end
		end
	end
	return out
end

