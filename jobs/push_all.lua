local function xor8(a, b)
	local hi = X4[(a // 16) * 16 + (b // 16) + 1]
	local lo = X4[(a % 16) * 16 + (b % 16) + 1]
	return hi * 16 + lo
end

-- FNV-1a 32, with the multiply decomposed as 16777619 = 2^24 + 2^8 + 147 so
-- every intermediate stays below 2^41 and is exact in a double. A naive
-- h * 16777619 with h < 2^32 exceeds 2^53 and rounds (verified 2026-10-07).
local function fnv(s)
	local h = 2166136261
	for i = 1, #s do
		local lo = h % 256
		h = h - lo + xor8(lo, s:byte(i))
		h = (h * 147 + h * 256 + (h % 256) * 16777216) % 4294967296
	end
	return h
end

