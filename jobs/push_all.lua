	if sup.wall then
		return CFrame.lookAt(pos, pos - sup.wall.normal)
	end
	local look = Vector3.new(destination.LookVector.X, 0, destination.LookVector.Z)
	if look.Magnitude > 0.1 then
		return CFrame.lookAt(pos, pos + look.Unit)
