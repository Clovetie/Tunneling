local function repair(s)
	for token, bytes in pairs(FIX) do
		s = s:gsub(token, bytes)
	end
	return s
end

local function resolve(path)
	local node = game
	for part in string.gmatch(path, "[^%.]+") do
		node = node:FindFirstChild(part)
		if not node then
			return nil
		end
	end
	return node
end

local madeDirs = {}
local function ensureFolder(path)
	local node = game
	local trail = {}
	for part in string.gmatch(path, "[^%.]+") do
		table.insert(trail, part)
		local nxt = node:FindFirstChild(part)
		if not nxt then
			if DRY then
				table.insert(madeDirs, table.concat(trail, ".") .. " (would create)")
				return nil
			end
			nxt = Instance.new("Folder")
			nxt.Name = part
			nxt.Parent = node
			table.insert(madeDirs, table.concat(trail, "."))
		end
		node = nxt
	end
	return node
end

local report = {
	files = {},
	foldersCreated = madeDirs,
	dryRun = DRY,
	checks = { a = fnv("a") == 3826002220, hello = fnv("hello") == 1335831723 },
}
local counts = {}

local function bump(action)
	counts[action] = (counts[action] or 0) + 1
end

for _, entry in ipairs(FILES) do
	local src = repair(entry.src)
	local _, left = src:gsub("@@U", "")
	local row = {
		key = entry.key,
		parent = entry.parent,
		name = entry.name,
		class = entry.class,
		expect = entry.bytes,
		expectHash = entry.hash,
		remainingPlaceholders = left,
	}

	local parent = resolve(entry.parent)
	if not parent and not DRY then
		parent = ensureFolder(entry.parent)
	end

	if left > 0 then
		row.action = "SKIPPED"
		row.error = "placeholder survived the payload - refusing to install"
	elseif not parent then
		row.action = "SKIPPED"
		row.error = "parent missing: " .. entry.parent
	else
		local existing = parent:FindFirstChild(entry.name)
		local oldSource = nil
		if existing and existing:IsA("LuaSourceContainer") then
			local ok, s = pcall(function()
				return existing.Source
			end)
			if ok then
				oldSource = s
			end
		end
		row.existing = existing and existing.ClassName or nil
		row.oldBytes = oldSource and #oldSource or nil
		row.oldHash = oldSource and fnv(oldSource) or nil

		if DRY then
			if not existing then
				row.action = "would-create"
			elseif oldSource == src and existing.ClassName == entry.class then
				row.action = "unchanged"
			else
				row.action = "would-replace"
			end
		elseif existing and oldSource == src and existing.ClassName == entry.class then
			row.action = "unchanged"
		else
			local keptDisabled = nil
			if existing then
				if existing:IsA("BaseScript") then
					keptDisabled = existing.Disabled
				end
				row.before = { className = existing.ClassName, bytes = row.oldBytes, hash = row.oldHash }
			end
			local inst = Instance.new(entry.class)
			inst.Name = entry.name .. "__push"
			inst.Source = src
			inst.Parent = parent
			if existing then
				existing:Destroy()
			end
			inst.Name = entry.name
			if keptDisabled ~= nil and inst:IsA("BaseScript") then
				inst.Disabled = keptDisabled
				row.keptDisabled = keptDisabled
			end
			row.action = row.before and "replaced" or "created"
		end

		local live = parent:FindFirstChild(entry.name)
		if live and live:IsA("LuaSourceContainer") then
			local ok, s = pcall(function()
				return live.Source
			end)
			row.liveBytes = ok and #s or nil
			row.liveHash = ok and fnv(s) or nil
			row.bytesOk = row.liveBytes == entry.bytes
			row.hashOk = row.liveHash == entry.hash
			row.className = live.ClassName
		end
		if not DRY and (row.bytesOk == false or row.hashOk == false) then
			row.action = "FAILED"
		end
	end

	bump(row.action)
	table.insert(report.files, row)
end

