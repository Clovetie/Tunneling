"""
Build `jobs/push_all.lua` — a self-contained job that publishes the ENTIRE
NightLoop package from this repo into the live place.

This is the generic replacement for the three-file `make_push.py`: same tricks
it needed (new instances instead of in-place `.Source`, ASCII-only payload,
byte-count verification), plus:

  * every script of the package, not three - `nightloop/src/**` and
    `nightloop/client/**`, i.e. the Rojo tree of `default.project.json`
  * an FNV-1a 32 hash per file, computed here and re-checked on the installed
    source with the exact-in-double decomposition, so "installed" means
    byte-identical rather than "looks about right"
  * unchanged files are left untouched (and the job says so), so one Ctrl+Z
    undoes only what actually changed
  * `--dry` builds `jobs/push_all_dry.lua`: identical logic, no writes - the
    live-vs-repo diff for every file in one read-only pass
  * keeps the old instance's `Disabled` flag across a replacement

Usage:
    python3 jobs/make_push_all.py            -> jobs/push_all.lua
    python3 jobs/make_push_all.py --dry      -> jobs/push_all_dry.lua
    python3 relay/relay.py push --dry        # generate + run, from the sandbox
"""

