import re  # noqa: E402


def _lua_bytes(escaped):
    """Turn a Lua short-string body into bytes the way Luau would."""
    out = bytearray()
    i = 0
    while i < len(escaped):
        if escaped[i] == "\\" and i + 1 < len(escaped) and escaped[i + 1].isdigit():
            j = i + 1
            while j < len(escaped) and j < i + 4 and escaped[j].isdigit():
                j += 1
            out.append(int(escaped[i + 1:j]) & 0xFF)
            i = j
        else:
            out.extend(escaped[i].encode("utf-8"))
            i += 1
    return bytes(out)


FIX_RE = re.compile(r'\["(@@U[0-9A-F]{4}@@)"\] = "((?:\\\d{1,3})*)",')
ENTRY_RE = re.compile(
    r'key = "(?P<key>[^"]+)",.*?'
    r'bytes = (?P<bytes>\d+),\s*'
    r'hash = (?P<hash>\d+),\s*'
    r'src = \[=====\[\n(?P<src>.*?)\]=====\],',
    re.S,
)


def verify(path):
    """Re-decode the generated payload and compare with the repo files."""
    text = open(path, encoding="ascii").read()
    fix = {token: _lua_bytes(raw) for token, raw in FIX_RE.findall(text)}
    entries = list(ENTRY_RE.finditer(text))
    if not entries:
        raise SystemExit(f"{path}: no entries found - verifier is out of date")

    problems = []
    for match in entries:
        key = match.group("key")
        rel = next((r for r, k in MANIFEST if k == key), None)
        if rel is None:
            problems.append(f"{key}: not in the manifest")
            continue
        payload = match.group("src").encode("ascii")
        for token, real in fix.items():
            payload = payload.replace(token.encode("ascii"), real)
        with open(os.path.join(ROOT, rel), "rb") as fh:
            repo = fh.read()
        want_bytes, want_hash = int(match.group("bytes")), int(match.group("hash"))
        if payload != repo:
            problems.append(f"{key}: payload differs from {rel} "
                            f"({len(payload)} vs {len(repo)} bytes)")
        if want_bytes != len(repo):
            problems.append(f"{key}: recorded size {want_bytes} != {len(repo)}")
        if want_hash != fnv1a32(repo):
            problems.append(f"{key}: recorded hash {want_hash} != {fnv1a32(repo)}")
    if len(entries) != len(MANIFEST):
        problems.append(f"{len(entries)} entries for {len(MANIFEST)} manifest files")
    if problems:
        print(f"FAILED verification of {path}:")
        for line in problems[:10]:
            print("  -", line)
        raise SystemExit(1)
    print(f"verified {path}: {len(entries)} payloads decode byte-identical to the repo")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true", help="build the read-only diff job")
    ap.add_argument("--both", action="store_true", help="build both jobs")
    ap.add_argument("--no-verify", action="store_true",
                    help="skip re-decoding the generated payload")
    args = ap.parse_args()

    targets = []
    if args.both:
        targets = [(False, OUT_REAL), (True, OUT_DRY)]
    elif args.dry:
        targets = [(True, OUT_DRY)]
    else:
        targets = [(False, OUT_REAL)]

    for dry, out in targets:
        body = build(dry)
        with open(out, "w", encoding="ascii", newline="\n") as fh:
            fh.write(body)
        print(f"wrote {out} ({len(body)} bytes, ASCII-only, {len(MANIFEST)} files)")
        if not args.no_verify:
            verify(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
