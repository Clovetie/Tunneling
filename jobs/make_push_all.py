FILE_TMPL = """\t{
\t\tkey = "%(key)s",
\t\tparent = "%(parent)s",
\t\tname = "%(name)s",
\t\tclass = "%(class)s",
\t\tbytes = %(bytes)d,
\t\thash = %(hash)d,
\t\tsrc = [=====[
%(src)s]=====],
\t},
"""


def utf8_escapes(text):
    """Lua source with every non-ASCII byte escaped, plus the placeholder map."""
    out = []
    fixes = {}
    for ch in text:
        code = ord(ch)
        if code < 128:
            out.append(ch)
            continue
        token = "@@U%04X@@" % code
        if token not in fixes:
            fixes[token] = "".join("\\%d" % b for b in ch.encode("utf-8"))
        out.append(token)
    return "".join(out), fixes


def build(dry):
    files, all_fixes = [], {}
    for rel, key in MANIFEST:
        parent, name, cls = TREE[key]
        with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
            raw = fh.read()
        if "]=====]" in raw:
            raise SystemExit(f"{rel}: contains the long-string terminator ]=====]")
        src, fixes = utf8_escapes(raw)
        for token in fixes:
            if token in raw:
                raise SystemExit(f"{rel}: contains the literal placeholder {token}")
        all_fixes.update(fixes)
        fnv_hash, size = digest(rel)   # digest() returns (hash, bytes)
        files.append(FILE_TMPL % {
            "key": key, "parent": parent, "name": name, "class": cls,
            "bytes": size, "hash": fnv_hash, "src": src,
        })

    fix = "\n".join('\t["%s"] = "%s",' % (tok, esc) for tok, esc in sorted(all_fixes.items()))
    purpose = ("DRY RUN: reports, for every file, whether the live copy differs from the repo -\n"
               "\tand writes NOTHING. Run jobs/push_all.lua to actually publish." if dry else
               "Publishes the repo's NightLoop package into the LIVE place, replacing only the\n"
               "\tfiles whose source actually differs.")
    body = HEADER % {
        "out": "push_all_dry.lua" if dry else "push_all.lua",
        "purpose": purpose,
        "count": len(files),
        "fix": fix,
        "dry": "true" if dry else "false",
        "files": "\n".join(files) + "\n",
    } + BODY

    bad = [(i, c) for i, c in enumerate(body) if ord(c) > 127]
    if bad:
        raise SystemExit(f"job file is not ASCII at {bad[:5]}")
    return body


