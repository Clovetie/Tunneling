# --- Gameplay Engineer ------------------------------------------------------

def gameplay_engineer(ctx):
    mechanic = _mechanic_for(ctx.objective)
    bundle = ctx.call("build_gameplay_mechanic", {"mechanic": mechanic, "installInStudio": False}, kind="read")
    namespaces = {
        "ReplicatedStorage.Shared": ("ReplicatedStorage", "ReplicatedStorage.ArenaTeam_Gameplay"),
        "ServerScriptService": ("ServerScriptService", "ServerScriptService.ArenaTeam_Gameplay"),
        "StarterPlayer.StarterPlayerScripts": ("StarterPlayer.StarterPlayerScripts",
                                               "StarterPlayer.StarterPlayerScripts.ArenaTeam_Gameplay"),
    }
    for _, (parent, target) in namespaces.items():
        _ensure_folder(ctx, parent, target.rsplit(".", 1)[-1], target)
    written = []
    for script in bundle.get("scripts") or []:
        parent, target_ns = namespaces.get(script.get("targetParent"), namespaces["ServerScriptService"])
        source = str(script.get("source") or "")
        check = ctx.call("luau_check", {"code": source}, kind="read")
        if not check.get("ok"):
            raise PolicyError("luau_syntax_error", f"Generated mechanic script {script['name']} failed luau_check")
        class_name = "LocalScript" if target_ns.startswith("StarterPlayer") else (
            "ModuleScript" if script["name"].endswith(("Config", "Catalog", "Trees")) or "RoundConfig" in script["name"] else "Script"
        )
        target = f"{target_ns}.{script['name']}"
        ctx.call("write_script", {
            "parent": target_ns, "name": script["name"], "className": class_name,
            "source": source, "dm": "edit", "validateSyntax": True,
        }, kind="write", target=target, summary=f"Install server/client gameplay script {target}")
        written.append({"path": target, "className": class_name, "bytes": len(source)})
    net = ctx.try_call("audit_network_security", {"includeStudio": True}, kind="read")
    ctx.results["gameplay"] = {"mechanic": mechanic, "scriptCount": len(written), "scripts": written,
                               "source": "roblox-kit/systems/mechanics", "networkAudit": _compact(net)}
    ctx.artifact("gameplay", f"Installed {len(written)} server-authoritative gameplay script(s) for '{mechanic}'",
                 data=ctx.results["gameplay"])
    return ctx.done(f"Installed '{mechanic}' gameplay system ({len(written)} validated scripts)",
                    gameplay=ctx.results["gameplay"])


def _mechanic_for(objective: str) -> str:
    text = (objective or "").lower()
    for word, mechanic in (("npc", "dialogue-npc"), ("dialog", "dialogue-npc"),
                           ("combat", "combat-abilities"), ("boss", "boss-encounter"),
                           ("loot", "inventory-loot"), ("chest", "loot-chest"),
                           ("inventory", "inventory-loot"), ("quest", "task-generator"),
                           ("round", "round-survival"), ("survival", "round-survival")):
        if word in text:
            return mechanic
    return "round-survival"


# --- QA Engineer ------------------------------------------------------------

def qa_engineer(ctx):
    caps = ctx.try_call("playtest_capabilities", {}, kind="read", allow_no_peer=True)
    scenario = ctx.call("run_playtest_scenario", {
        "mode": "run", "warmupSeconds": 0.2, "keepAlive": False,
        "serverCode": "return { arenaTeamQa = true, place = game.Name }",
        "consoleLimit": 100, "timeout": 45,
    }, kind="verify", summary="Run a playtest scenario with a live server probe and console inspection")
    if not scenario.get("ok"):
        raise PolicyError("playtest_failed", f"Playtest scenario failed: {scenario.get('reason') or scenario.get('error')}")
    console = ctx.try_call("get_console_output", {"level": "Error", "source": "game",
                                                  "dm": "edit", "limit": 100}, kind="read")
    error_lines = _error_lines(console) + list(scenario.get("runtimeErrors") or [])
    read_backs = []
    for path in _written_script_paths(ctx.project):
        row = ctx.call("script_read", {"path": path, "dm": "edit"}, kind="read")
        ok = bool(str(row.get("source") or "").strip())
        read_backs.append({"path": path, "ok": ok, "bytes": len(str(row.get("source") or ""))})
        if not ok:
            raise PolicyError("verification_failed", f"Persisted script {path} is missing after playtest")
    _capture_viewport(ctx, "qa_final", "iso_ne", "Workspace")
    ctx.results["qa"] = {
        "scenario": {k: scenario.get(k) for k in ("ok", "mode", "consoleCount", "sessionStopped",
                                                   "serverPeerSeen", "clientPeerSeen", "phaseTimings")},
        "serverProbe": _compact(scenario.get("serverResult")),
        "errorLines": error_lines[:20], "errorCount": len(error_lines),
        "readBacks": read_backs, "capabilities": _compact(caps),
    }
    ctx.artifact("qa", f"Playtest + console inspection: {len(error_lines)} error(s), {len(read_backs)} read-back(s)",
                 data=ctx.results["qa"])
    if error_lines:
        raise PolicyError("runtime_errors", f"QA found {len(error_lines)} console error(s): "
                          + "; ".join(str(e)[:160] for e in error_lines[:3]))
    return ctx.done(f"Playtest passed with {len(read_backs)} persisted-script read-back(s) and no console errors",
                    qa=ctx.results["qa"])


def _error_lines(console) -> list:
    if not isinstance(console, dict):
        return []
    out = []
    for line in console.get("lines") or []:
        if not isinstance(line, dict):
            continue
        level = str(line.get("type") or line.get("level") or "").lower()
        if "error" in level:
            out.append(str(line.get("message") or line.get("text") or ""))
    return out


