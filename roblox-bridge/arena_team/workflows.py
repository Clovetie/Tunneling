# --- shared helpers ---------------------------------------------------------

def _compact(value, limit: int = 1400) -> dict:
    """Keep result payloads bounded for the dashboard and persisted context."""
    if not isinstance(value, dict):
        return {"value": str(value)[:limit]}
    try:
        text = json.dumps(value, ensure_ascii=False, default=str)
    except (TypeError, ValueError):
        text = str(value)
    return json.loads(text[:limit]) if len(text) <= limit else {"preview": text[:limit] + "…", "truncated": True}


def _capture_viewport(ctx, label: str, preset: str, path: str, include_hud: bool = False):
    filename = re.sub(r"[^A-Za-z0-9_\-]", "_", f"{ctx.project['id']}_{label}")[:100] + ".png"
    target = ctx.orch.store.evidence_path(filename)
    result = ctx.try_call("capture_viewport", {
        "preset": preset, "path": path, "includeHud": include_hud,
        "width": 560, "height": 315, "returnInline": False, "saveFile": str(target),
    }, kind="read")
    if isinstance(result, dict) and result.get("ok") and Path(str(target)).is_file():
        ctx.evidence("viewport", filename, f"{preset} viewport evidence",
                     meta={"preset": preset, "path": path, "includeHud": include_hud})
    else:
        # No fake evidence: a failed capture is a visible warning, not a green tick.
        ctx.warnings.append(f"viewport evidence '{label}' unavailable: "
                            f"{(result or {}).get('reason', 'capture failed')}")
    return result


