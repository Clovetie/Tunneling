def _js_string(value: str) -> str:
    """Produce a Luau string literal (JSON is valid Luau for simple ASCII strings)."""
    text = str(value or "").replace("\n", " ").replace("\r", " ")[:220]
    text = re.sub(r"[^\x20-\x7e]", " ", text)
    return json.dumps(text, ensure_ascii=True)


def _ensure_folder(ctx, parent: str, name: str, target: str):
    """Create an exclusive namespace folder once; never destroy an existing one."""
    existing = ctx.try_call("inspect_instance", {"path": target, "depth": 0, "dm": "edit"},
                            kind="read", allow_missing=True)
    if isinstance(existing, dict) and existing.get("name"):
        return {"created": False, "path": target}
    row = ctx.call("build_tree", {
        "parent": parent,
        "tree": [{"name": name, "className": "Folder", "replaceExisting": True}],
        "select": False,
        "dm": "edit",
    }, kind="write", target=target, summary=f"Create owned namespace {target}")
    return {"created": True, "path": target, "result": row}


def _written_script_paths(project: dict) -> list:
    paths = []
    for task in project.get("plan", {}).get("tasks", []):
        for path, receipt in (task.get("verification") or {}).items():
            if isinstance(receipt, dict) and receipt.get("tool") == "script_read":
                paths.append(path)
    return sorted(set(paths))


# --- Project Manager --------------------------------------------------------

def project_manager(ctx):
    if ctx.task.get("key") == "analysis":
        return _analysis(ctx)
    if ctx.task.get("key") == "design":
        return _design(ctx)
    return _report(ctx)


def _analysis(ctx):
    state = ctx.try_call("get_studio_state", {}, kind="read")
    diag = ctx.try_call("diagnose_connection", {}, kind="read")
    fleet = ctx.try_call("studio_fleet", {"action": "list"}, kind="read")
    survey = ctx.try_call("survey_place", {"includeSource": False, "maxScriptBytes": 60000},
                          kind="read", allow_no_peer=True)
    selection = ctx.try_call("manage_selection", {"action": "get"}, kind="read", allow_no_peer=True)
    caps = ctx.try_call("playtest_capabilities", {}, kind="read", allow_no_peer=True)
    totals = (survey.get("totals") or {}) if isinstance(survey, dict) else {}
    studio = (state.get("studio") or {}) if isinstance(state, dict) else {}
    peers = (fleet.get("studios") or fleet.get("peers") or []) if isinstance(fleet, dict) else []
    online = [p for p in peers if p.get("online")]
    edit_peer = next((p for p in online if p.get("dm") == "edit"), online[0] if online else {})
    studio_info = studio.get("place") if isinstance(studio.get("place"), dict) else {}
    place_name = (studio.get("name") or studio_info.get("name")
                  or (studio.get("place") if isinstance(studio.get("place"), str) else "") or "unknown")
    place_id = studio.get("placeId") or studio_info.get("placeId") or studio.get("place_id") or 0
    analysis = {
        "studioState": state,
        "diagnosis": diag,
        "survey": survey,
        "selection": selection,
        "playtestCapabilities": caps,
        "fleet": fleet,
        "place": place_name,
        "placeId": place_id,
        "studioConnected": bool(state.get("studioConnected")),
        "peerId": edit_peer.get("peerId"),
        "activeDataModel": edit_peer.get("dm") or "edit",
        "peerCount": len(online),
        "surveyTotals": {k: totals.get(k) for k in ("scripts", "instances", "remotes", "total", "guis") if k in totals},
        "warnings": list(ctx.warnings),
    }
    ctx.results["analysis"] = analysis
    ctx.artifact("analysis", f"Place survey: {json.dumps(analysis['surveyTotals'])}",
                 data={"studioConnected": analysis["studioConnected"], "peerId": analysis["peerId"]})
    n = analysis["surveyTotals"].get("scripts", 0)
    return ctx.done(
        f"Surveyed '{analysis['place']}' — {n} script(s), {analysis['peerCount']} Studio peer(s), "
        f"connected={analysis['studioConnected']}",
        analysis=analysis,
    )


def _design(ctx):
    skills = ctx.try_call("search_skills", {"query": "roblox studio workflow", "limit": 5,
                                             "includeReferences": True}, kind="read")
    tools = ctx.try_call("search_tools", {"query": "write_script survey_place playtest", "limit": 8}, kind="read")
    matches = (skills.get("results") or []) if isinstance(skills, dict) else []
    applied = None
    if matches:
        applied = ctx.try_call("apply_skill", {"name": matches[0]["name"]}, kind="read")
    design = ctx.orch.plan_design(ctx.project)
    ctx.results["design"] = design
    ctx.results["discoveredTools"] = [t.get("name") for t in ((tools.get("results") or []) if isinstance(tools, dict) else [])]
    ctx.results["skillApplied"] = (applied or {}).get("name") if isinstance(applied, dict) else None
    ctx.artifact("design", design["title"], data={"components": len(design["components"]),
                                                   "generatedBy": design["generatedBy"]})
    return ctx.done(f"Technical design produced with {len(design['components'])} owned components", design=design)


def _report(ctx):
    report = ctx.orch.build_report(ctx.project)
    ctx.results["report"] = report
    ctx.artifact("report", report["title"], data={"verified": report["verified"],
                                                   "taskCount": len(report["tasks"])})
    ctx.orch.post_bus(ctx.spec.key, "Development report ready",
                      f"{report['title']} · verified={report['verified']}",
                      kind="result", project=ctx.project)
    return ctx.done(report["title"], report=report)


# --- Lead Developer ---------------------------------------------------------

def lead_developer(ctx):
    survey = ctx.try_call("survey_place", {"includeSource": False}, kind="read", allow_no_peer=True)
    paths = _written_script_paths(ctx.project)
    reviews = []
    for path in paths:
        row = ctx.call("script_read", {"path": path, "dm": "edit"}, kind="read")
        source = str(row.get("source") or "")
        check = ctx.call("luau_check", {"code": source}, kind="read")
        reviews.append({"path": path, "bytes": len(source), "luauOk": bool(check.get("ok")),
                        "filesFailed": check.get("filesFailed", 0)})
        if not check.get("ok"):
            raise PolicyError("review_failed", f"Luau re-check failed for {path}: {check.get('results')}")
    snapshots = ctx.try_call("manage_snapshots", {"action": "list"}, kind="read")
    ctx.results["review"] = {"scripts": reviews, "surveyTotals": (survey.get("totals") or {}),
                             "snapshotCount": len((snapshots.get("snapshots") or [])) if isinstance(snapshots, dict) else 0}
    ctx.artifact("review", f"Reviewed {len(reviews)} script(s), all Luau checks passed",
                 data={"paths": paths})
    return ctx.done(f"Integration review passed for {len(reviews)} script(s)", review=ctx.results["review"])


# --- World Builder ----------------------------------------------------------

def world_builder(ctx):
    namespace = "Workspace.ArenaTeam_World"
    created = _ensure_folder(ctx, "Workspace", "ArenaTeam_World", namespace)
    query = _world_query(ctx.objective)
    assets = ctx.try_call("search_assets", {"query": query, "assetType": "model", "limit": 5}, kind="read")
    caps = ctx.try_call("mesh_capabilities", {}, kind="read", allow_no_peer=True)
    spawn = ctx.call("spawn_kit_mesh", {
        "query": query, "category": "props", "parent": namespace,
        "position": [0, 6, 0], "scale": 1.0, "spawnInStudio": True,
    }, kind="write", target=namespace, summary=f"Spawn licensed 3D mesh ('{query}') into the owned world folder")
    if not spawn.get("spawnedInStudio"):
        raise PolicyError("verification_failed", "spawn_kit_mesh reported spawnedInStudio=false; no Studio change was applied")
    model_path = f"{namespace}.{spawn['modelName']}"
    found = ctx.try_call("inspect_instance", {"path": model_path, "depth": 1, "dm": "edit"}, kind="read")
    if not isinstance(found, dict) or not found.get("name"):
        raise PolicyError("verification_failed", f"Spawned mesh {model_path} could not be inspected in the Edit DataModel")
    ctx.task.setdefault("verification", {})[model_path] = {
        "tool": "inspect_instance", "readBack": True, "className": found.get("className") or found.get("class") or "Model"
    }
    audit = ctx.try_call("audit_3d_scene", {"path": namespace, "autoFixUnanchored": False,
                                            "snapFloating": False}, kind="read")
    _capture_viewport(ctx, "world_perspective", "perspective", "Workspace")
    ctx.results["world"] = {
        "folder": created, "query": query, "mesh": spawn.get("modelName"),
        "meshPrioritized": spawn.get("meshPrioritized"), "catalogMatches": spawn.get("catalogMatchCount"),
        "assetMatches": (assets.get("totalMatches") if isinstance(assets, dict) else 0),
        "meshCapabilities": caps.get("supported") if isinstance(caps, dict) else None,
        "sceneAudit": _compact(audit), "verifiedPath": model_path,
    }
    ctx.artifact("world", f"Mesh-first environment built at {model_path}", data=ctx.results["world"])
    return ctx.done(f"Built mesh-first world '{spawn['modelName']}' and verified it in the Edit DataModel",
                    world=ctx.results["world"])


def _world_query(objective: str) -> str:
    text = (objective or "").lower()
    for word, query in (("crystal", "crystal"), ("portal", "portal"), ("shrine", "shrine"),
                        ("forest", "tree"), ("nature", "tree"), ("dungeon", "dungeon"),
                        ("space", "scifi"), ("castle", "castle"), ("rune", "rune")):
        if word in text:
            return query
    return "crystal"


# --- Luau Engineer ----------------------------------------------------------

def luau_engineer(ctx):
    namespace = "ServerScriptService.ArenaTeam_Scripts"
    created = _ensure_folder(ctx, "ServerScriptService", "ArenaTeam_Scripts", namespace)
    objective_literal = _js_string(ctx.objective)
    project_literal = _js_string(ctx.project["id"])
    sources = [
        ("ArenaTeamConfig", "ModuleScript",
         CONFIG_MODULE.replace("__OBJECTIVE__", objective_literal).replace("__PROJECT_ID__", project_literal)),
        ("ArenaTeamBootstrap", "Script", BOOTSTRAP_SCRIPT),
    ]
    written = []
    for name, class_name, source in sources:
        check = ctx.call("luau_check", {"code": source}, kind="read")
        if not check.get("ok"):
            raise PolicyError("luau_syntax_error", f"luau_check rejected {name}: {check.get('results')}")
        target = f"{namespace}.{name}"
        ctx.call("write_script", {
            "parent": namespace, "name": name, "className": class_name,
            "source": source, "dm": "edit", "validateSyntax": True,
        }, kind="write", target=target, summary=f"Write validated Luau {class_name} {target}")
        read_back = ctx.call("script_read", {"path": target, "dm": "edit"}, kind="read")
        written.append({"path": target, "className": class_name, "bytes": len(str(read_back.get("source") or "")),
                        "luauChecks": check.get("checksPerformed") or check.get("results", [{}])[0].get("checksPerformed")})
    ctx.results["luau"] = {"folder": created, "scripts": written}
    ctx.artifact("luau", f"Wrote and read back {len(written)} validated Luau script(s)", data=ctx.results["luau"])
    return ctx.done(f"Wrote {len(written)} validated Luau script(s) into the Edit DataModel", luau=ctx.results["luau"])


# --- UI/UX Designer ---------------------------------------------------------

def ui_ux_designer(ctx):
    target = "StarterGui.ArenaTeam_UI_HUD"
    icons = ctx.try_call("search_cloud_icons", {"query": _icon_query(ctx.objective), "limit": 8}, kind="read")
    imported = ctx.call("import_ui_from_web", {
        "preset": "rpg_hud", "guiName": "ArenaTeam_UI_HUD", "parent": "StarterGui",
        "deSlop": True, "installInStudio": True,
    }, kind="write", target=target, summary="Install responsive ScreenGui with de-slopped HUD copy")
    if not imported.get("installedInStudio"):
        raise PolicyError("verification_failed", "import_ui_from_web reported installedInStudio=false")
    inspected = ctx.try_call("inspect_instance", {"path": target, "depth": 2, "dm": "edit"}, kind="read")
    if not isinstance(inspected, dict) or not inspected.get("name"):
        raise PolicyError("verification_failed", f"Installed ScreenGui {target} could not be inspected")
    ctx.task.setdefault("verification", {})[target] = {
        "tool": "inspect_instance", "readBack": True, "children": len(inspected.get("children") or [])
    }
    layout = ctx.try_call("audit_ui_layout", {"path": target, "viewports": ["desktop", "tablet", "mobile"]}, kind="read")
    _capture_viewport(ctx, "ui_hud", "perspective", "Workspace", include_hud=True)
    ctx.results["ui"] = {
        "path": target, "elements": imported.get("elementsConverted"),
        "deSlopApplied": imported.get("deSlopApplied"),
        "iconMatches": (icons.get("count") or icons.get("total")) if isinstance(icons, dict) else 0,
        "inspectedChildren": len(inspected.get("children") or []),
        "layoutAudit": _compact(layout),
    }
    ctx.artifact("ui", f"Responsive HUD installed at {target} (desktop/tablet/mobile audit)", data=ctx.results["ui"])
    return ctx.done(f"Installed {target} and audited desktop/tablet/mobile layouts", ui=ctx.results["ui"])


